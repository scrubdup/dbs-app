/**
 * PIKK Party Line room policy — server-side building block, NOT a deployed chat service.
 * Every "session" must come from trusted server authentication + age assurance.
 * Never accept ageAssured, accountStatus, userId, roomId, or event IDs directly
 * from an unverified browser request. Persistent storage, transport, abuse
 * detection, and cross-device delivery must be implemented before launch.
 */
export const PARTY_LINE_LIMITS = Object.freeze({
  maxParticipants: 10, // larger rooms require an SFU and a separate scaling review
  maxMessageLength: 1000,
  maxRoomNameLength: 64,
});

function deny(message) {
  throw new Error(message);
}
function idOf(value) {
  if (typeof value !== 'string' || !/^[a-zA-Z0-9_-]{1,80}$/.test(value)) deny('Invalid identifier');
  return value;
}
export function requireAdultSession(session) {
  if (!session || typeof session !== 'object') deny('Authentication required');
  const userId = idOf(session.userId);
  if (session.accountStatus !== 'active') deny('Account not active');
  if (session.ageAssured !== true) deny('Verified adult eligibility required');
  return userId;
}
function requireMember(room, session) {
  const userId = requireAdultSession(session);
  const member = room.members.find((m) => m.userId === userId);
  if (!member) deny('Room membership required');
  return member;
}
function requireHost(room, session) {
  const member = requireMember(room, session);
  if (member.role !== 'host') deny('Host permission required');
  return member;
}
function requireOpen(room) {
  if (!room || room.closed) deny('Room is closed');
}
function validateName(name) {
  const text = String(name ?? '').trim();
  if (!text || text.length > PARTY_LINE_LIMITS.maxRoomNameLength) deny('Invalid room name');
  return text;
}
function memberOf(userId, role = 'listener') {
  return { userId, role, muted: role === 'listener', wantsToSpeak: false };
}

/** id must be generated by the trusted server, not by a client. */
export function createPartyRoom({ id, name, visibility = 'public', owner, createdAt = Date.now() }) {
  const ownerId = requireAdultSession(owner);
  if (!['public', 'private'].includes(visibility)) deny('Invalid visibility');
  if (!Number.isSafeInteger(createdAt) || createdAt < 0) deny('Invalid timestamp');
  return {
    id: idOf(id), name: validateName(name), visibility, ownerId,
    members: [memberOf(ownerId, 'host')], invitedIds: [],
    blockedIds: [], messages: [], reports: [], closed: false, createdAt,
  };
}
export function inviteToPartyRoom(room, actor, targetId) {
  requireOpen(room);
  requireHost(room, actor);
  const userId = idOf(targetId);
  if (room.blockedIds.includes(userId)) deny('User blocked');
  if (room.members.some((m) => m.userId === userId)) return room;
  return { ...room, invitedIds: [...new Set([...room.invitedIds, userId])] };
}
export function joinPartyRoom(room, session) {
  requireOpen(room);
  const userId = requireAdultSession(session);
  if (room.blockedIds.includes(userId)) deny('User blocked');
  if (room.members.some((m) => m.userId === userId)) return room;
  if (room.visibility === 'private' && !room.invitedIds.includes(userId)) deny('Invite required');
  if (room.members.length >= PARTY_LINE_LIMITS.maxParticipants) deny('Room is full');
  return {
    ...room,
    members: [...room.members, memberOf(userId)],
    invitedIds: room.invitedIds.filter((id) => id !== userId),
  };
}
export function requestPartyMic(room, session) {
  requireOpen(room);
  const member = requireMember(room, session);
  if (member.role !== 'listener') return room;
  return { ...room, members: room.members.map((m) =>
    m.userId === member.userId ? { ...m, wantsToSpeak: true } : m) };
}
export function approvePartyMic(room, actor, targetId) {
  requireOpen(room);
  requireHost(room, actor);
  const userId = idOf(targetId);
  const target = room.members.find((m) => m.userId === userId);
  if (!target || !target.wantsToSpeak) deny('No speaking request');
  return { ...room, members: room.members.map((m) =>
    m.userId === userId ? { ...m, role: 'speaker', wantsToSpeak: false, muted: true } : m) };
}
export function setPartyMute(room, actor, targetId, muted) {
  requireOpen(room);
  const actorId = requireAdultSession(actor);
  const target = room.members.find((m) => m.userId === idOf(targetId));
  if (!target) deny('Member not found');
  if (actorId !== target.userId) requireHost(room, actor);
  else requireMember(room, actor);
  if (typeof muted !== 'boolean') deny('Invalid mute state');
  // A host may silence someone, but may never activate another person's mic.
  // Unmuting is a consent-only action performed by the speaker themself.
  if (!muted && actorId !== target.userId) deny('Only the member can unmute their microphone');
  if (target.role === 'listener' && !muted) deny('Listeners cannot unmute');
  // This is a policy state only; actual microphone publication must be gated server-side.
  return { ...room, members: room.members.map((m) =>
    m.userId === target.userId ? { ...m, muted } : m) };
}
export function sendPartyMessage(room, session, { id, text, sentAt = Date.now() }) {
  requireOpen(room);
  const member = requireMember(room, session);
  const body = String(text ?? '').trim();
  if (!body || body.length > PARTY_LINE_LIMITS.maxMessageLength) deny('Invalid message');
  if (!Number.isSafeInteger(sentAt) || sentAt < 0) deny('Invalid timestamp');
  const messageId = idOf(id); // generated by server; deduplicate retries
  if (room.messages.some((m) => m.id === messageId)) return room;
  return { ...room, messages: [...room.messages, {
    id: messageId, userId: member.userId, text: body, sentAt,
  }] };
}
export function reportPartyMember(room, actor, targetId, reason, reportId) {
  requireOpen(room);
  const reporter = requireMember(room, actor);
  const target = idOf(targetId);
  if (target === reporter.userId) deny('Cannot report yourself');
  if (!room.members.some((m) => m.userId === target)) deny('Member not found');
  const why = String(reason ?? '').trim();
  if (!why || why.length > 500) deny('Invalid report reason');
  const id = idOf(reportId); // trusted server ID
  if (room.reports.some((r) => r.id === id)) return room;
  return { ...room, reports: [...room.reports, {
    id, reporterId: reporter.userId, targetId: target, reason: why,
  }] };
}
export function removePartyMember(room, actor, targetId, { block = false } = {}) {
  requireOpen(room);
  requireHost(room, actor);
  const target = idOf(targetId);
  if (target === room.ownerId) deny('Host cannot remove themselves');
  if (!room.members.some((m) => m.userId === target)) deny('Member not found');
  return { ...room, members: room.members.filter((m) => m.userId !== target),
    invitedIds: room.invitedIds.filter((id) => id !== target),
    blockedIds: block ? [...new Set([...room.blockedIds, target])] : room.blockedIds };
}
export function leavePartyRoom(room, session) {
  requireOpen(room);
  const userId = requireMember(room, session).userId;
  const members = room.members.filter((m) => m.userId !== userId);
  if (!members.length) return { ...room, members, closed: true };
  if (userId !== room.ownerId) return { ...room, members };
  const newHostId = members[0].userId;
  return { ...room, ownerId: newHostId, members: members.map((m) =>
    m.userId === newHostId ? { ...m, role: 'host', muted: true, wantsToSpeak: false } : m) };
}
